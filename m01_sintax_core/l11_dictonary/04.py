# Программа должна:
# Вывести количество элементов в каждом словаре.
# Проверить, пустой ли каждый словарь, и вывести соответствующее сообщение.
# Для проверки пустоты словаря нужно создать функцию check_empty

# Напишите тут ваш код

dict1 = {
    "name": "Sergey",
    "last_name": "Todoriko"
}

dict2 = {
    "name": "Olga",
    "last_name": "Manaenkova",
    "age": 36
}


def check_empty(dict):
    if len(dict) == 0:
        print("Словарь пустой")
    else:
        print(f"Словарь {dict} не пустой")
        print(f"Количество элементов: {len(dict)}")

check_empty(dict1)
check_empty(dict2)