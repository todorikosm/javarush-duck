# Напишите тут ваш код

book_info = {
    "title": "Таинственный остров",
    "author": "Жюль Верн",
    "year": 1817
}

book_info["year"] = 1888
print(book_info)

print("\n")

if "издательство" not in book_info:
    book_info.setdefault("издательство", "СТ")
print(book_info)

print("\n")

updates = {"title": "ТО", "year": 1999}
book_info.update(updates)
print(book_info)