# Метод find() возвращает индекс первого вхождения подстроки в строку, если подстрока найдена, и -1,
# если подстрока отсутствует. Это позволяет не только проверить наличие подстроки, но и узнать её положение.

text = "Hello, world!"
position = text.find("world")
print(position)  # Выведет: 7



# Похож на find(), но вместо возвращения -1 при отсутствии подстроки, метод index() генерирует исключение ValueError.
# Этот метод полезен, когда отсутствие подстроки является неожиданным и должно привести к ошибке.

text = "Hello, world!"
try:
    position = text.index("world")
    print(position)  # Выведет: 7
except ValueError:
    print("Substring not found.")



# Метод count() подсчитывает, сколько раз подстрока встречается в строке. Это полезно, когда нужно знать не только
# факт вхождения, но и количество вхождений.

text = "Hello, world!"
cnt = text.count("l")
print(cnt)  # Выведет: 3
