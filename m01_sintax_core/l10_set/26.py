# Объединение и пересечение

# Напишите программу, которая создает два множества из элементов, запрашиваемых у пользователя.
# Программа должна объединить эти множества с использованием метода union() и найти их пересечение с использованием метода intersection().
# Программа должна вывести оба результата

# Напишите тут ваш код

# Запрашиваем у пользователя элементы для первого множества
my_set1 = set(map(int, input("Введите элементы первого множества через пробел: ").split()))

# Запрашиваем у пользователя элементы для второго множества
my_set2 = set(map(int, input("Введите элементы второго множества через пробел: ").split()))

# Объединение множеств
union_set = my_set1.union(my_set2)
print("Объединение множеств:", union_set)

# Пересечение
intersection_set = my_set1.intersection(my_set2)
print("Пересечение множеств:", intersection_set)