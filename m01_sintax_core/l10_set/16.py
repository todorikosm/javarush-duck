# Фруктовица

# Напишите программу, которая создает множество, содержащее названия нескольких фруктов.
# Затем программа должна запросить у пользователя название фрукта для удаления и удалить его из множества с
# использованием метода discard().
# Программа должна вывести обновленное множество.
# Если такого фрукта в множестве нет, программа не должна падать с ошибкой — метод discard() как раз это и обеспечивает.

# Напишите тут ваш код

fruits_set = {"апельсин", "банан", "виноград"}

need_delete = input("Введите название фрукта для удаления: ")

fruits_set.discard(need_delete)
print(fruits_set)

