# Метод pop() может быть использован в цикле для поочередного удаления всех элементов из множества,
# пока оно не станет пустым.

my_set = {1, 2, 3, 4, 5}
print("Исходное множество:", my_set)

while my_set:
    removed_el = my_set.pop()
    print(f"Удалён элемент: {removed_el}, Оставшееся множество: {my_set}")

print("Множество пустое:", my_set)
