# Когда оператор del используется для удаления множества, это множество больше не существует,
# и все его элементы удаляются из памяти

my_set = {1, 2, 3, 4, 5}
print("Исходное множество:", my_set)

# Удаление множества
del my_set

# Попытка доступа к удаленному множеству вызовет ошибку
# print(my_set) # NameError: name 'my_set' is not defined


