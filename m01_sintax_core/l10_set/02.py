# Уникальный список.

# Напишите программу, которая создает список из 10 элементов, запрашиваемых у пользователя.
# Затем программа должна создать множество из элементов списка, чтобы оставить только уникальные элементы,
# и вывести полученное множество.

# Напишите тут ваш код

my_list = []

while len(my_list) < 10:
    value = input("Введите значение: ")
    my_list.append(value)

list_to_set = set(my_list)
print(list_to_set)