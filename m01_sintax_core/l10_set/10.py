# Случайные множества

# Напишите программу, которая сгенерирует:
# Один список случайных элементов от 0 до 99.
# Второй список случайных элементов от 50 до 125.
# Затем преобразуйте списки во множества.
# Добавьте первое множество ко второму.
# Выведите количество элементов полученного множества на экран.

import random

# Генерация списков случайных элементов
list1 = [random.randint(0, 100) for _ in range(100)]
list2 = [random.randint(50, 125) for _ in range(100)]

# Преобразование списков во множества
set1 = set(list1)
set2 = set(list2)

# Объединение множеств
union_set = set1.union(set2)

# Вывод количества элементов полученного множества
print(len(union_set))
