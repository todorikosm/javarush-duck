# В этом примере мы инициализируем переменную max_value первым элементом кортежа.
# Затем мы итерируем по всем элементам кортежа, сравнивая каждый элемент с текущим максимальным значением и обновляя
# max_value, если находим большее значение.

my_tuple = (5, 17, 23, 11, 2)
max_value = my_tuple[0]

for number in my_tuple:
    if number > max_value:
        max_value = number

print(f"Максимальное значение в кортеже: {max_value}")