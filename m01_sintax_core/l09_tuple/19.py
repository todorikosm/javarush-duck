# Так же, как и у списка, у элементов кортежа есть индексы, поэтому можно обойти его элементы с
# помощью цикла for (в сочетании с функцией range()). Это позволяет работать не только с самими элементами,
# но и с их позициями, что бывает необходимо при выполнении более сложных манипуляций с данными.

my_tuple = ('a', 'b', 'c', 'd')
for i in range(len(my_tuple)):
    print(f'index: {i}, Element: {my_tuple[i]}')